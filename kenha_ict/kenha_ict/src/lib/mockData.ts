export type LicenseStatus = 'Active' | 'Expiring Soon' | 'Expired' | 'Renewed';
export type AssetStatus = 'In Use' | 'Under Maintenance' | 'Decommissioned';
export type ContractStatus = 'Active' | 'Under Review' | 'Expiring' | 'Expired' | 'Terminated';
export type SlaTier = 'Platinum' | 'Gold' | 'Silver' | 'Bronze';

// ICT Asset Issuance types
export type IctAssetType = 'Printer' | 'PC' | 'Scanner' | 'Mouse' | 'Laptop' | 'Projector' | 'Monitor' | 'Keyboard' | 'Switch' | 'UPS';
export type IctAssetStatus = 'Issued' | 'Available' | 'Damaged' | 'Under Maintenance' | 'Due for Maintenance' | 'Decommissioned';

export interface IctAsset {
  id: string;
  assetTag: string;
  type: IctAssetType;
  model: string;
  serialNumber: string;
  manufacturer: string;
  department: string;
  location: string;
  status: IctAssetStatus;
  issuedTo: string | null;
  issuedDate: string | null;
  purchaseDate: string;
  warrantyExpiry: string;
  costKES: number;
  notes: string;
}

export interface License {
  id: string;
  name: string;
  vendor: string;
  category: 'Security' | 'Productivity' | 'Infrastructure' | 'Development' | 'Connectivity' | 'ERP';
  department: string;
  status: LicenseStatus;
  expiryDate: string;
  annualCostKES: number;
  seatsTotal: number;
  seatsUsed: number;
  licenseKey: string;
  renewalContact: string;
  notes: string;
}

export interface Asset {
  id: string;
  name: string;
  vendor: string;
  category: 'Laptop' | 'Server' | 'Network' | 'Printer' | 'UPS' | 'Display';
  department: string;
  status: AssetStatus;
  purchaseDate: string;
  warrantyExpiry: string;
  costKES: number;
  serialNumber: string;
  assignedTo: string;
  location: string;
}

export interface Supplier {
  id: string;
  name: string;
  category: string;
  contactPerson: string;
  phone: string;
  email: string;
  address: string;
  activeContracts: number;
  totalContractValueKES: number;
  rating: number;
}

export interface Contract {
  id: string;
  refNumber: string;
  name: string;
  supplierId: string;
  supplierName: string;
  valueKES: number;
  startDate: string;
  endDate: string;
  slaTier: SlaTier;
  status: ContractStatus;
  department: string;
  description: string;
  milestones: { label: string; date: string; completed: boolean }[];
}

export interface BudgetItem {
  id: string;
  description: string;
  category: 'Software' | 'Hardware' | 'Connectivity' | 'Services' | 'Security';
  department: string;
  allocatedKES: number;
  consumedKES: number;
  invoiceRef: string;
  date: string;
}

